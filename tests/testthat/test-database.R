test_that("DB reads are bounded and identifiers are quoted", {
  skip_if_not_installed("DBI"); skip_if_not_installed("RSQLite")
  con <- DBI::dbConnect(RSQLite::SQLite(),":memory:"); on.exit(DBI::dbDisconnect(con))
  DBI::dbWriteTable(con,"odd name",data.frame(id=1:3))
  expect_equal(nrow(dq_db_read(con,"odd name")),3L)
  expect_error(dq_db_read(con,"odd name",max_rows=2),class="dq_capacity_error")
  expect_error(dq_db_read(con,"odd name; DROP TABLE x"))
  expect_true(DBI::dbExistsTable(con,"odd name"))
})
test_that("run storage rejects duplicate run IDs transactionally", {
  skip_if_not_installed("DBI"); skip_if_not_installed("RSQLite")
  con <- DBI::dbConnect(RSQLite::SQLite(),":memory:"); on.exit(DBI::dbDisconnect(con)); dq_db_init(con)
  r <- dq_run(data.frame(x=-1),dq_spec("x","range","x",list(min=0)))
  dq_db_store(con,r); expect_error(dq_db_store(con,r))
  expect_equal(nrow(DBI::dbReadTable(con,"dq_runs")),1L)
  expect_equal(nrow(DBI::dbReadTable(con,"dq_findings")),1L)
})
test_that("routing retains all rows exactly once across three destinations", {
  skip_if_not_installed("DBI"); skip_if_not_installed("RSQLite")
  con <- DBI::dbConnect(RSQLite::SQLite(),":memory:"); on.exit(DBI::dbDisconnect(con)); dq_db_init(con)
  d <- data.frame(x=c(1,-1)); r <- dq_run(d,dq_spec("x","range","x",list(min=0)))
  for(t in c("accepted","quarantine","held")) DBI::dbWriteTable(con,t,d[FALSE,,drop=FALSE])
  dq_db_route(con,d,r,"accepted","quarantine","held")
  expect_equal(nrow(DBI::dbReadTable(con,"accepted")),0L)
  expect_equal(nrow(DBI::dbReadTable(con,"quarantine")),1L)
  expect_equal(nrow(DBI::dbReadTable(con,"held")),1L)
  expect_error(dq_db_route(con,d,r,"accepted","quarantine","held"))
  expect_equal(nrow(DBI::dbReadTable(con,"quarantine")),1L)
})
test_that("routing failure rolls back the receipt and earlier writes", {
  skip_if_not_installed("DBI"); skip_if_not_installed("RSQLite")
  con <- DBI::dbConnect(RSQLite::SQLite(),":memory:"); on.exit(DBI::dbDisconnect(con)); dq_db_init(con)
  DBI::dbExecute(con,"CREATE TABLE accepted (x REAL)")
  DBI::dbExecute(con,"CREATE TABLE quarantine (x REAL CHECK (x >= 0))")
  DBI::dbExecute(con,"CREATE TABLE held (x REAL)")
  d <- data.frame(x=c(1,-1)); r <- dq_run(d,dq_spec("x","range","x",list(min=0),max_fail_rate=.5))
  expect_error(dq_db_route(con,d,r,"accepted","quarantine","held"))
  expect_equal(nrow(DBI::dbReadTable(con,"dq_routes")),0L)
  expect_equal(nrow(DBI::dbReadTable(con,"accepted")),0L)
})
test_that("database ledger updates require the expected current head", {
  skip_if_not_installed("DBI"); skip_if_not_installed("RSQLite")
  con <- DBI::dbConnect(RSQLite::SQLite(),":memory:"); on.exit(DBI::dbDisconnect(con)); dq_db_init(con)
  r <- dq_run(data.frame(x=-1),dq_spec("x","range","x",list(min=0)))
  l <- dq_issues(r); genesis <- dq_issues()$head
  dq_db_save_ledger(con,l,expected_head=genesis)
  expect_identical(dq_db_load_ledger(con)$head,l$head)
  expect_error(dq_db_save_ledger(con,l,expected_head=genesis))
  next_l <- dq_transition(l,l$events$issue_id[1],"triaged","reviewer","Assigned")
  dq_db_save_ledger(con,next_l,expected_head=l$head)
  expect_identical(dq_db_load_ledger(con)$head,next_l$head)
})
test_that("SQLite text primary keys are not misreported as explicit NOT NULL", {
  skip_if_not_installed("DBI"); skip_if_not_installed("RSQLite")
  con <- DBI::dbConnect(RSQLite::SQLite(),":memory:"); on.exit(DBI::dbDisconnect(con))
  DBI::dbExecute(con,"CREATE TABLE survey (id TEXT PRIMARY KEY, x REAL)")
  dict <- data.frame(name=c("id","x"),type=c("character","numeric"),required=c(TRUE,FALSE))
  ct <- dq_contract("survey","1",dict,"id",grain="entity",owner="steward",purpose="test")
  a <- dq_db_audit(con,"survey",ct)
  expect_identical(a$status[a$control_id=="db.not_null.id"],"not_evaluated")
  expect_identical(a$status[a$control_id=="db.constraint_semantics"],"not_evaluated")
})
