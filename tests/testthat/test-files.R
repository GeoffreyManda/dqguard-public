test_that("original CSV headers and uneven rows are audited", {
  p <- tempfile(fileext = ".csv"); on.exit(unlink(p))
  writeLines(c("id,id", "a,b"), p)
  a <- dq_file_audit(p)
  expect_identical(a$status[a$control_id == "columns.unique"], "fail")
  expect_identical(a$status[a$control_id == "file.encryption_access_policy"], "not_evaluated")
  writeLines(c("id,x", "a,1,2"), p)
  a <- dq_file_audit(p)
  expect_identical(a$status[a$control_id == "file.inspection"], "not_evaluated")
})
test_that("unavailable oversized and unsupported files do not pass inspection", {
  a <- dq_file_audit(tempfile(fileext = ".csv"))
  expect_identical(a$status[1], "fail")
  p <- tempfile(fileext = ".csv"); on.exit(unlink(p)); writeLines(c("id", "a"), p)
  a <- dq_file_audit(p, max_bytes = 1)
  expect_identical(a$status[a$control_id == "file.size_limit"], "not_evaluated")
  expect_error(dq_file_audit(p, header_row = 1e10))
})
