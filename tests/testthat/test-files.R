test_that("XLSX inspection distinguishes filter arrows from active criteria", {
  skip_if_not_installed("xml2")
  if (!nzchar(Sys.which("zip"))) skip("zip executable unavailable")
  root <- tempfile(); dir.create(root); old <- getwd()
  on.exit({setwd(old); unlink(root, recursive = TRUE)}, add = TRUE)
  dir.create(file.path(root, "xl", "_rels"), recursive = TRUE)
  dir.create(file.path(root, "xl", "worksheets"), recursive = TRUE)
  writeLines('<workbook xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Data" sheetId="1" r:id="rId1"/></sheets></workbook>', file.path(root, "xl", "workbook.xml"))
  writeLines('<Relationships><Relationship Id="rId1" Target="worksheets/sheet1.xml"/></Relationships>', file.path(root,"xl","_rels","workbook.xml.rels"))
  sheet <- '<worksheet><sheetData><row r="1"><c r="A1" t="inlineStr"><is><t>id</t></is></c></row><row r="2"><c r="A2" t="inlineStr"><is><t>a</t></is></c></row></sheetData><autoFilter ref="A1:A2"/></worksheet>'
  writeLines(sheet, file.path(root,"xl","worksheets","sheet1.xml"))
  setwd(root); utils::zip("test.xlsx", list.files("xl", recursive = TRUE, full.names = TRUE), flags = "-q")
  a <- dq_file_audit(file.path(root, "test.xlsx"))
  expect_identical(a$status[a$control_id == "xlsx.no_active_filters"], "pass")
  expect_identical(a$status[a$control_id == "columns.unique"], "pass")
  writeLines(sub('<autoFilter ref="A1:A2"/>', '<autoFilter ref="A1:A2"><filterColumn colId="0"><filters><filter val="a"/></filters></filterColumn></autoFilter>', sheet, fixed = TRUE), file.path(root,"xl","worksheets","sheet1.xml"))
  utils::zip("test.xlsx", list.files("xl", recursive = TRUE, full.names = TRUE), flags = "-q")
  b <- dq_file_audit(file.path(root,"test.xlsx"))
  expect_identical(b$status[b$control_id == "xlsx.no_active_filters"], "fail")
})
test_that("XLSX inspection reports separators, unnamed columns, text numbers, spaces and highlighted cells", {
  skip_if_not_installed("xml2")
  if (!nzchar(Sys.which("zip"))) skip("zip executable unavailable")
  root <- tempfile(); dir.create(root); old <- getwd()
  on.exit({setwd(old); unlink(root, recursive = TRUE)}, add = TRUE)
  dir.create(file.path(root, "xl", "_rels"), recursive = TRUE); dir.create(file.path(root, "xl", "worksheets"), recursive = TRUE)
  writeLines('<workbook xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="Data" sheetId="1" r:id="rId1"/></sheets></workbook>', file.path(root, "xl", "workbook.xml"))
  writeLines('<Relationships><Relationship Id="rId1" Target="worksheets/sheet1.xml"/></Relationships>', file.path(root, "xl", "_rels", "workbook.xml.rels"))
  writeLines('<styleSheet><fills count="3"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill><fill><patternFill patternType="solid"><fgColor rgb="FFFFFF00"/></patternFill></fill></fills><cellXfs count="2"><xf fillId="0"/><xf fillId="2"/></cellXfs></styleSheet>', file.path(root, "xl", "styles.xml"))
  is <- function(ref, t, s = 0) sprintf('<c r="%s" t="inlineStr" s="%d"><is><t xml:space="preserve">%s</t></is></c>', ref, s, t)
  sheet <- paste0('<worksheet><sheetData>',
    '<row r="1">', is("A1", "id"), is("B1", "amount"), '</row>',
    '<row r="2">', is("A2", "r1"), is("B2", "12"), is("C2", "extra"), '</row>',
    '<row r="3">', is("A3", "1111"), is("B3", "1111"), is("C3", "1111"), '</row>',
    '<row r="4">', is("A4", " r2 ", 1), '<c r="B4"><v>5</v></c></row>',
    '</sheetData><autoFilter ref="A1:B4"/></worksheet>')
  writeLines(sheet, file.path(root, "xl", "worksheets", "sheet1.xml"))
  setwd(root); utils::zip("t.xlsx", list.files("xl", recursive = TRUE, full.names = TRUE), flags = "-q")
  a <- dq_file_audit(file.path(root, "t.xlsx"))
  st <- function(id) a$status[a$control_id == id]
  expect_identical(st("structure.separator_rows"), "fail")
  expect_identical(st("columns.named_positions"), "fail")
  expect_identical(st("format.numbers_as_text"), "fail")
  expect_identical(st("format.text_whitespace"), "fail")
  expect_identical(st("processing.highlighted_cells"), "needs_review")
  expect_identical(st("xlsx.saved_filter_buttons"), "needs_review")
  expect_identical(st("xlsx.no_active_filters"), "pass")
})
