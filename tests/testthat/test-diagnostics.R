test_that("profiling reports missingness without changing values", {
  d <- data.frame(x = c(1, 2, NA), region = c("a", "a", "b"))
  p <- dq_profile(d)
  expect_equal(p$n_missing[p$field == "x"], 1L)
  expect_equal(p$missing_rate[p$field == "x"], 1/3)
  expect_equal(d$x, c(1, 2, NA))
})
test_that("conditional missingness has an eligibility denominator", {
  d <- data.frame(x = c(NA, NA, 1))
  m <- dq_missingness(d, applicability = list(x = c(FALSE, TRUE, TRUE)))
  expect_equal(m$rates$n_applicable, 2L)
  expect_equal(m$rates$missing_rate, .5)
  expect_match(m$interpretation, "do not establish")
})
test_that("drift does not infer a breach without thresholds", {
  a <- data.frame(x = 1:40); b <- data.frame(x = 101:140)
  d <- dq_drift(a, b)
  expect_identical(d$status, "descriptive")
  d <- dq_drift(a, b, ks_threshold = .2)
  expect_identical(d$status, "needs_review")
  expect_identical(dq_drift(a[1:2,,drop=FALSE], b)$status, "not_evaluated")
})
test_that("reconciliation never turns missing groups or unknown totals into zero", {
  a <- data.frame(g = c("a", "b"), x = c(1, NA_real_))
  b <- data.frame(g = c("a", "b", "c"), x = c(1, 2, 0))
  z <- dq_reconcile(a, b, "g", "x")
  expect_true("not_evaluated" %in% z$status)
  expect_true("missing_current_group" %in% z$reason)
  expect_true(any(z$status == "fail"))
})
test_that("frame coverage counts unique units and out-of-frame rows", {
  a <- data.frame(id = c("a", "a", "x")); f <- data.frame(id = c("a", "b"))
  c <- dq_coverage(a, f, "id")
  expect_equal(c$metrics$coverage, .5)
  expect_equal(c$metrics$n_out_of_frame, 1L)
  expect_equal(c$missing_frame_rows, 2L)
  expect_error(dq_coverage(a, rbind(f, f[1,,drop=FALSE]), "id"))
})
test_that("survey anomalies are described as signals not fraud findings", {
  t <- as.POSIXct("2026-01-01", tz = "UTC")
  d <- data.frame(e = c("a", "a"), start = c(t, t + 10), end = c(t + 100, t + 20), sub = c(t + 200, t + 200), answer = c("yes", "yes"))
  s <- dq_survey_signals(d, "e", "start", "end", 30, "sub", "answer")
  expect_true(all(c("short_duration", "overlapping_interviews", "repeated_submission_time", "identical_response_pattern") %in% s$code))
  expect_true(all(grepl("not evidence", s$interpretation)))
})
test_that("geofence optional adapter handles inside outside and missing positions", {
  skip_if_not_installed("sf")
  ring <- rbind(c(-1,-1), c(1,-1), c(1,1), c(-1,1), c(-1,-1))
  boundary <- sf::st_sfc(sf::st_polygon(list(ring)), crs = 4326)
  d <- data.frame(lat = c(0, 5, NA), lon = c(0, 5, NA))
  expect_equal(dq_geofence(d, "lat", "lon", boundary), c(TRUE, FALSE, NA))
})
