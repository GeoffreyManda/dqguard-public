test_that("Whipple's index takes its documented extremes and bands", {
  expect_equal(dq_whipple(rep(c(25, 30, 35, 40), 10))$index, 500)
  expect_identical(dq_whipple(rep(c(25, 30, 35, 40), 10))$band, "very rough")
  expect_equal(dq_whipple(23:62)$index, 100)
  expect_identical(dq_whipple(23:62)$band, "highly accurate")
  expect_true(is.na(dq_whipple(c(30, 40))$index))
})
test_that("Benford MAD is near zero for a Benford sample and large for a uniform one", {
  x <- 10^seq(0, 6, length.out = 20000)
  b <- dq_benford(x)
  expect_lt(b$mad, 0.006)
  expect_identical(b$band, "close conformity")
  u <- dq_benford(rep(c(500, 600, 700, 800, 900), 40))
  expect_identical(u$band, "nonconformity")
  expect_true(is.na(dq_benford(1:5)$mad))
})
test_that("percent match finds clones and respects the joint-answer minimum", {
  d <- as.data.frame(matrix(c(rep(letters[1:12], 2), LETTERS[1:12]), nrow = 3, byrow = TRUE), stringsAsFactors = FALSE)
  pm <- dq_percent_match(d, min_joint = 10)
  expect_equal(pm$max_match[1], 1); expect_equal(pm$twin[1], 2)
  expect_equal(pm$max_match[3], 0)
  expect_true(all(is.na(dq_percent_match(d, min_joint = 13)$max_match)))
})
test_that("last-digit preference is detected against uniform and against a reference", {
  heaped <- rep(c(10, 20, 30, 40, 50), 30)
  expect_lt(dq_last_digit(heaped)$p_value, 0.001)
  expect_gt(dq_last_digit(heaped, reference = rep(c(15, 20, 35), 50))$p_value, -1)
  expect_true(is.na(dq_last_digit(1:10)$p_value))
})
test_that("peer z-scores are computed within groups and undefined for single members", {
  z <- dq_peer_z(c(1, 2, 3, 10, 5), c("a", "a", "a", "a", "b"))
  expect_gt(z[4], 1.4); expect_true(is.na(z[5]))
})
test_that("sensitivity sweeps return curves and robust flags", {
  x <- c(1, 5, 9)
  s <- dq_sensitivity(function(t) x > t, grid = c(2, 4, 6), ids = c("a", "b", "c"))
  expect_equal(s$curve$flagged, c(2, 2, 1))
  expect_identical(s$robust, "c"); expect_identical(sort(s$any), c("b", "c"))
  expect_error(dq_sensitivity(function(t) 1, grid = 1))
})
test_that("the 44-item checklist catalogue maps every item to controls", {
  cl <- dq_catalog("checklist")
